/// One closed enum, emitted twice: the union every client type is checked
/// against, and a runtime array carrying the same members in the same order.
///
/// The array is the half a test can iterate. A TypeScript union leaves no
/// trace at run time, so a sweep over "every value of this enum" had to be
/// written out by hand beside the union, and the day Rust gained a member the
/// sweep silently stopped covering it while still passing. `FORM_GROUPS` and
/// `JOB_EVENT_KINDS` were emitted this way one at a time; every closed enum
/// gets it now, so no caller has to ask for one first.
fn closed<T, F: Fn(&T) -> String>(name: &str, constant: &str, values: &[T], render: F) -> String {
    use core::fmt::Write;
    let members: Vec<String> = values.iter().map(render).collect();
    let mut out = format!("export type {name} =\n  | {};\n", members.join("\n  | "));
    // infallible on String; the Result is the trait's, not the writer's
    let _unused: core::fmt::Result =
        writeln!(out, "\nexport const {constant}: readonly {name}[] = [");
    for member in &members {
        let _unused: core::fmt::Result = writeln!(out, "  {member},");
    }
    out.push_str("];\n");
    out
}

fn serde_name<T: serde::Serialize>(value: &T) -> String {
    serde_json::to_string(value).unwrap_or_else(|_| "\"unrepresentable\"".to_owned())
}

/// Which artefact this run prints. One binary rather than three, because the
/// three read the same Rust constants and a second binary would be a second
/// place for an import to go stale.
fn main() {
    let which = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "vocab".to_owned());
    let out = match which.as_str() {
        "vocab" => vocab(),
        "plans-ts" => plans_ts(),
        "plans-js" => plans_js(),
        other => {
            eprintln!("unknown artefact {other}; the set is vocab, plans-ts and plans-js");
            std::process::exit(2);
        }
    };
    print!("{out}");
}

