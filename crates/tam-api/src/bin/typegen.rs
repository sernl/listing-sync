//! The vocabulary generator: TypeScript unions and the plan table emitted
//! from the same closed Rust enums and constants the cross-layer tests pin,
//! so no client's copy can drift from the server's without a build failing.
//!
//! Three artefacts, selected by the one argument: `vocab` (the default) is
//! the console's closed unions, `plans-ts` is the console's plan table, and
//! `plans-js` is the landing build's copy of the same table as plain ESM.
//! The landing page is a static Astro build with no API to call, so it reads
//! a generated module rather than a second hand-written price list — which
//! is what it had, and what disagreed with the console's.
//!
//! Output goes to stdout; `just web-typegen` writes each into its place and
//! `just web-check` fails if regeneration changes any committed file.

