//! The vocabulary generator: TypeScript unions emitted from the same closed
//! Rust enums the cross-layer tests pin, so the client's vocabulary cannot
//! drift from the server's without a build failing. Output goes to stdout;
//! `just web-typegen` writes it into the client and `just web-check` fails
//! if regeneration changes the committed file.

