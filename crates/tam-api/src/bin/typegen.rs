//! The vocabulary generator: TypeScript unions emitted from the same closed
//! Rust enums the cross-layer tests pin, so the client's vocabulary cannot
//! drift from the server's without a build failing. Output goes to stdout;
//! `just web-typegen` writes it into the client and `just web-check` fails
//! if regeneration changes the committed file.

#![forbid(unsafe_code)]

use tam_api::jobs::{outcome_str, JobPhase, ALL_OUTCOMES};
use tam_api::{APIErrorCode, APIErrorKind};
use tam_domain::equivalence::{ElectionTriggerKind, LossKind};
use tam_storage::ItemStateKind;
use tam_types::{
    ConnectionEvent, ConnectionStatus, FailureCode, InventoryId, JobEventPayload, Marketplace,
    TermKind,
};

fn union<T, F: Fn(&T) -> String>(name: &str, values: &[T], render: F) -> String {
    let members: Vec<String> = values.iter().map(render).collect();
    format!("export type {name} =\n  | {};\n", members.join("\n  | "))
}

fn serde_name<T: serde::Serialize>(value: &T) -> String {
    serde_json::to_string(value).unwrap_or_else(|_| "\"unrepresentable\"".to_owned())
}

fn main() {
    let mut out = String::new();
    out.push_str("// Generated by tam-typegen. Do not edit; run `just web-typegen`.\n\n");
    out.push_str(&union("FailureCode", &FailureCode::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("APIErrorCode", &APIErrorCode::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("APIErrorKind", &APIErrorKind::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("InventoryId", &InventoryId::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("Marketplace", &Marketplace::ALL, serde_name));
    out.push('\n');
    out.push_str(&union(
        "ConnectionStatus",
        &ConnectionStatus::ALL,
        serde_name,
    ));
    out.push('\n');
    out.push_str(&union("ConnectionEvent", &ConnectionEvent::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("ItemState", &ItemStateKind::ALL, |state| {
        format!("\"{}\"", state.as_str())
    }));
    out.push('\n');
    out.push_str(&union("ItemOutcome", &ALL_OUTCOMES, |outcome| {
        format!("\"{}\"", outcome_str(*outcome))
    }));
    out.push('\n');
    out.push_str(&union(
        "JobPhase",
        &[JobPhase::Active, JobPhase::Settled],
        serde_name,
    ));
    out.push('\n');
    out.push_str(&union("TermKind", &TermKind::ALL, serde_name));
    out.push('\n');
    // Emitted from `as_str` rather than from serde, because these two live in
    // tam-domain, which carries no serde dependency and does not acquire one
    // to shorten a generator.
    out.push_str(&union(
        "ElectionTriggerKind",
        &ElectionTriggerKind::ALL,
        |kind| format!("\"{}\"", kind.as_str()),
    ));
    out.push('\n');
    out.push_str(&union("LossKind", &LossKind::ALL, |kind| {
        format!("\"{}\"", kind.as_str())
    }));
    out.push('\n');
    out.push_str(&union(
        "JobEventKind",
        &JobEventPayload::ALL_KINDS,
        |kind| format!("\"{kind}\""),
    ));
    out.push_str("\nexport const JOB_EVENT_KINDS: readonly JobEventKind[] = [\n");
    for kind in JobEventPayload::ALL_KINDS {
        use core::fmt::Write;
        // infallible on String; the Result is the trait's, not the writer's
        let _unused: core::fmt::Result = writeln!(out, "  \"{kind}\",");
    }
    out.push_str("];\n");
    print!("{out}");
}
