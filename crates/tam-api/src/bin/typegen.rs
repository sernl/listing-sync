/// The plan table as TypeScript, beside the vocabulary rather than inside
/// it: the vocabulary file is unions, and this one is data with a shape.
fn plans_ts() -> String {
    let mut out = String::new();
    out.push_str("// Generated by tam-typegen. Do not edit; run `just web-typegen`.\n\n");
    out.push_str("import type { AiStatus, Plan, SupportLevel } from './vocab';\n\n");
    out.push_str(CAPABILITIES_TS);
    out.push_str(
        "\nexport interface PlanRow {\n  \
         readonly id: Plan;\n  \
         readonly name: string;\n  \
         readonly monthly_cents: number | null;\n  \
         readonly yearly_cents: number | null;\n  \
         readonly trial_days: number;\n  \
         readonly sold: boolean;\n  \
         readonly capabilities: Capabilities;\n}\n\n\
         export interface Rung {\n  \
         readonly up_to: number;\n  \
         readonly price_cents: number;\n}\n\n\
         export interface Founding {\n  \
         readonly discount_year_one_pct: number;\n  \
         readonly discount_ongoing_pct: number;\n  \
         readonly ongoing_years: number;\n  \
         readonly free_imports: number;\n  \
         readonly places: number;\n}\n\n\
         export interface AiOffer {\n  \
         readonly status: AiStatus;\n  \
         readonly included_fills: number;\n  \
         readonly add_on_fills: number;\n  \
         readonly add_on_cents: number;\n}\n\n\
         export interface PlansView {\n  \
         readonly plans: readonly PlanRow[];\n  \
         readonly import_ladder: readonly Rung[];\n  \
         readonly ladder_above: string;\n  \
         readonly founding: Founding;\n  \
         readonly ai: AiOffer;\n}\n\n",
    );
    out.push_str("export const PLANS: readonly PlanRow[] = [\n");
    out.push_str(&plan_rows("  "));
    out.push_str("] as const;\n\n");
    out.push_str("export const IMPORT_LADDER: readonly Rung[] = [\n");
    out.push_str(&ladder_rows("  "));
    out.push_str("] as const;\n\n");
    out.push_str(&lit(
        "export const LADDER_ABOVE = ",
        &json(LADDER_ABOVE),
        " as const;\n\n",
    ));
    out.push_str(&lit(
        "export const FOUNDING: Founding = ",
        &json(&FOUNDING),
        " as const;\n\n",
    ));
    out.push_str(&lit(
        "export const AI: AiOffer = ",
        &json(&AI),
        " as const;\n",
    ));
    out
}

/// The same table as plain ESM for the landing build, which is Astro and
/// reads no types. Frozen rather than merely exported, because the landing
/// page's own copy of these numbers is what this file exists to delete.
fn plans_js() -> String {
    let mut out = String::new();
    out.push_str("// Generated by tam-typegen. Do not edit; run `just web-typegen`.\n\n");
    out.push_str("export const PLANS = Object.freeze([\n");
    out.push_str(&plan_rows("  "));
    out.push_str("]);\n\n");
    out.push_str("export const IMPORT_LADDER = Object.freeze([\n");
    out.push_str(&ladder_rows("  "));
    out.push_str("]);\n\n");
    out.push_str(&lit(
        "export const LADDER_ABOVE = ",
        &json(LADDER_ABOVE),
        ";\n\n",
    ));
    out.push_str(&lit(
        "export const FOUNDING = Object.freeze(",
        &json(&FOUNDING),
        ");\n\n",
    ));
    out.push_str(&lit("export const AI = Object.freeze(", &json(&AI), ");\n"));
    out
}

/// The `Capabilities` interface, written out rather than derived: the field
/// list is the one place a reader checks what a plan can say, and a
/// generator that produced it from a serialised sample would silently narrow
/// `number | null` to `null` the day every plan happened to hold none.
const CAPABILITIES_TS: &str = "export interface Capabilities {
  readonly resources_max: number;
  readonly marketplaces_max: number;
  readonly storage_bytes_max: number;
  readonly import_spreadsheet: boolean;
  readonly import_marketplace: boolean;
  readonly duplicate_review: boolean;
  readonly publish_marketplaces_max: number;
  readonly edit_days_after_purchase: number | null;
  readonly migrations_per_month: number;
  readonly scheduling: boolean;
  readonly sync_pull_interval_secs: number | null;
  readonly auto_publish_rules: boolean;
  readonly templates_max: number;
  readonly collections_max: number;
  readonly labels_max: number;
  readonly analytics: boolean;
  readonly export: boolean;
  readonly devices_max: number;
  readonly ai_fills_per_month: number;
  readonly support: SupportLevel;
}
";

/// One row per plan, capabilities inline, so both clients render the pricing
/// table without a fetch.
fn plan_rows(indent: &str) -> String {
    PLANS.iter().fold(String::new(), |mut out, row| {
        let caps: Capabilities = row.id.capabilities(None);
        out.push_str(indent);
        out.push_str("{ \"id\": ");
        out.push_str(&json(&row.id));
        out.push_str(", \"name\": ");
        out.push_str(&json(row.name));
        out.push_str(", \"monthly_cents\": ");
        out.push_str(&json(&row.monthly_cents));
        out.push_str(", \"yearly_cents\": ");
        out.push_str(&json(&row.yearly_cents));
        out.push_str(", \"trial_days\": ");
        out.push_str(&json(&row.trial_days));
        out.push_str(", \"sold\": ");
        out.push_str(&json(&row.sold));
        out.push_str(", \"capabilities\": ");
        out.push_str(&json(&caps));
        out.push_str(" },\n");
        out
    })
}

fn ladder_rows(indent: &str) -> String {
    IMPORT_LADDER.iter().fold(String::new(), |mut out, rung| {
        out.push_str(&lit(indent, &json(rung), ",\n"));
        out
    })
}

/// One assignment, assembled rather than formatted into an existing buffer:
/// the lint table bans `format!` appended to a `String`, and three joined
/// pieces say what this is doing more plainly than a `write!` would.
fn lit(head: &str, value: &str, tail: &str) -> String {
    let mut out = String::with_capacity(head.len() + value.len() + tail.len());
    out.push_str(head);
    out.push_str(value);
    out.push_str(tail);
    out
}

fn json<T: serde::Serialize + ?Sized>(value: &T) -> String {
    serde_json::to_string(value).unwrap_or_else(|_| "null".to_owned())
}
