//! The vocabulary generator: TypeScript unions emitted from the same closed
//! Rust enums the cross-layer tests pin, so the client's vocabulary cannot
//! drift from the server's without a build failing. Output goes to stdout;
//! `just web-typegen` writes it into the client and `just web-check` fails
//! if regeneration changes the committed file.

#![forbid(unsafe_code)]

use tam_api::jobs::{outcome_str, JobPhase, ALL_OUTCOMES};
use tam_api::product::StandardsState;
use tam_api::quota::QuotaKind;
use tam_api::resources::{kind_str, role_str};
use tam_api::vocabulary::{
    BodyWire, CardinalityKind, DelegationKind, DirectionView, NonDelegableReason, PayloadFileRule,
    VocabularyKind,
};
use tam_api::{APIErrorCode, APIErrorKind};
use tam_domain::equivalence::{ElectionTriggerKind, LossKind};
use tam_domain::product::FormGroup;
use tam_storage::ItemStateKind;
use tam_types::{
    ConnectionEvent, ConnectionStatus, CopyFormat, FailureCode, FileKind, FileRole, InventoryId,
    JobEventPayload, LengthUnit, Marketplace, TermKind, TransportClass,
};

fn union<T, F: Fn(&T) -> String>(name: &str, values: &[T], render: F) -> String {
    let members: Vec<String> = values.iter().map(render).collect();
    format!("export type {name} =\n  | {};\n", members.join("\n  | "))
}

fn serde_name<T: serde::Serialize>(value: &T) -> String {
    serde_json::to_string(value).unwrap_or_else(|_| "\"unrepresentable\"".to_owned())
}

fn main() {
    let mut out = String::new();
    out.push_str("// Generated by tam-typegen. Do not edit; run `just web-typegen`.\n\n");
    out.push_str(&union("FailureCode", &FailureCode::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("APIErrorCode", &APIErrorCode::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("APIErrorKind", &APIErrorKind::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("InventoryId", &InventoryId::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("Marketplace", &Marketplace::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("TransportClass", &TransportClass::ALL, serde_name));
    out.push('\n');
    out.push_str(&union(
        "ConnectionStatus",
        &ConnectionStatus::ALL,
        serde_name,
    ));
    out.push('\n');
    out.push_str(&union("ConnectionEvent", &ConnectionEvent::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("ItemState", &ItemStateKind::ALL, |state| {
        format!("\"{}\"", state.as_str())
    }));
    out.push('\n');
    out.push_str(&union("ItemOutcome", &ALL_OUTCOMES, |outcome| {
        format!("\"{}\"", outcome_str(*outcome))
    }));
    out.push('\n');
    out.push_str(&union(
        "JobPhase",
        &[JobPhase::Active, JobPhase::Settled],
        serde_name,
    ));
    out.push('\n');
    out.push_str(&union("TermKind", &TermKind::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("CopyFormat", &CopyFormat::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("LengthUnit", &LengthUnit::ALL, serde_name));
    out.push('\n');
    // Emitted from the API's own spelling rather than from serde: an upload
    // handle and a product view both carry these lowercase tokens, and the
    // derive's PascalCase is a different vocabulary the client never sees.
    out.push_str(&union("FileKind", &FileKind::ALL, |kind| {
        format!("\"{}\"", kind_str(*kind))
    }));
    out.push('\n');
    out.push_str(&union("FileRole", &FileRole::ALL, |role| {
        format!("\"{}\"", role_str(*role))
    }));
    out.push('\n');
    out.push_str(&union("QuotaKind", &QuotaKind::ALL, |kind| {
        format!("\"{}\"", kind.as_str())
    }));
    out.push('\n');
    out.push_str(&union("NativeDirection", &DirectionView::ALL, serde_name));
    out.push('\n');
    out.push_str(&union(
        "NativeVocabularyKind",
        &VocabularyKind::ALL,
        serde_name,
    ));
    out.push('\n');
    out.push_str(&union("Cardinality", &CardinalityKind::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("Delegation", &DelegationKind::ALL, serde_name));
    out.push('\n');
    out.push_str(&union(
        "NonDelegableReason",
        &NonDelegableReason::ALL,
        serde_name,
    ));
    out.push('\n');
    out.push_str(&union("PayloadFileRule", &PayloadFileRule::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("BodyWire", &BodyWire::ALL, serde_name));
    out.push('\n');
    out.push_str(&union("StandardsState", &StandardsState::ALL, serde_name));
    out.push('\n');
    // From `token` rather than from serde: `FormGroup` lives in tam-domain,
    // which carries no serde dependency and does not acquire one to shorten a
    // generator.
    out.push_str(&union("FormGroup", &FormGroup::ALL, |group| {
        format!("\"{}\"", group.token())
    }));
    out.push_str("\nexport const FORM_GROUPS: readonly FormGroup[] = [\n");
    for group in FormGroup::ALL {
        use core::fmt::Write;
        // infallible on String; the Result is the trait's, not the writer's
        let _unused: core::fmt::Result = writeln!(out, "  \"{}\",", group.token());
    }
    out.push_str("];\n");
    out.push('\n');
    // Emitted from `as_str` rather than from serde, because these two live in
    // tam-domain, which carries no serde dependency and does not acquire one
    // to shorten a generator.
    out.push_str(&union(
        "ElectionTriggerKind",
        &ElectionTriggerKind::ALL,
        |kind| format!("\"{}\"", kind.as_str()),
    ));
    out.push('\n');
    out.push_str(&union("LossKind", &LossKind::ALL, |kind| {
        format!("\"{}\"", kind.as_str())
    }));
    out.push('\n');
    out.push_str(&union(
        "JobEventKind",
        &JobEventPayload::ALL_KINDS,
        |kind| format!("\"{kind}\""),
    ));
    out.push_str("\nexport const JOB_EVENT_KINDS: readonly JobEventKind[] = [\n");
    for kind in JobEventPayload::ALL_KINDS {
        use core::fmt::Write;
        // infallible on String; the Result is the trait's, not the writer's
        let _unused: core::fmt::Result = writeln!(out, "  \"{kind}\",");
    }
    out.push_str("];\n");
    print!("{out}");
}
